    const originalText = new WeakMap();
    const originalAttributes = new WeakMap();
    let originalTitle;

    function translated(value, language) {
        if (language === "fr") return value;
        const table = translations[language];
        if (!table) return value;
        if (table[value]) return table[value];
        const titleSeparator = " – AutoTuning TN";
        if (value.endsWith(titleSeparator)) {
            const pageTitle = value.slice(0, -titleSeparator.length);
            return `${table[pageTitle] || pageTitle}${titleSeparator}`;
        }
        return value;
    }

    function translateTextNode(node, language) {
        if (!originalText.has(node)) originalText.set(node, node.nodeValue);
        const source = originalText.get(node);
        const parts = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
        if (parts[2]) node.nodeValue = `${parts[1]}${translated(parts[2], language)}${parts[3]}`;
    }

    function translateAttributes(element, language) {
        for (const attribute of ["placeholder", "title", "aria-label", "alt"]) {
            if (!element.hasAttribute(attribute)) continue;
            let originals = originalAttributes.get(element);
            if (!originals) {
                originals = new Map();
                originalAttributes.set(element, originals);
            }
            if (!originals.has(attribute)) originals.set(attribute, element.getAttribute(attribute));
            element.setAttribute(attribute, translated(originals.get(attribute), language));
        }
    }

    function translateAddedContent(node, language) {
        if (node.nodeType === Node.TEXT_NODE) {
            if (node.nodeValue.trim()) translateTextNode(node, language);
            return;
        }
        if (node.nodeType !== Node.ELEMENT_NODE || node.matches("script, style, .language-select")) return;
        const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
        let textNode;
        while ((textNode = walker.nextNode())) {
            if (textNode.nodeValue.trim()) translateTextNode(textNode, language);
        }
        translateAttributes(node, language);
        node.querySelectorAll("[placeholder], [title], [aria-label], img[alt]")
            .forEach(element => translateAttributes(element, language));
    }

    function applyLanguage(language) {
        const supported = ["fr", "en", "ar"].includes(language) ? language : "fr";
        language = supported;
        const root = document.documentElement;
        root.lang = supported;
        root.dir = supported === "ar" ? "rtl" : "ltr";

        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            if (!node.nodeValue.trim() || node.parentElement.closest("script, style, .language-select")) continue;
            translateTextNode(node, supported);
        }

        document.querySelectorAll("[placeholder], [title], [aria-label], img[alt]").forEach(element => {
            translateAttributes(element, supported);
        });

        const title = document.querySelector("title");
        if (title) {
            if (originalTitle === undefined) originalTitle = title.textContent;
            title.textContent = translated(originalTitle, supported);
        }
        const selector = document.getElementById("language-select");
        if (selector && selector.value !== supported) selector.value = supported;
    }

    const selector = document.getElementById("language-select");
    let language = "fr";
    try {
        language = localStorage.getItem("autotuning-language") || "fr";
    } catch {
        language = "fr";
    }
    applyLanguage(language);

    if (selector) {
        selector.addEventListener("change", () => {
            const selected = selector.value;
            try {
                localStorage.setItem("autotuning-language", selected);
            } catch {
                // The selected language still applies for this page if storage is unavailable.
            }
            applyLanguage(selected);
        });
    }

    new MutationObserver(records => {
        for (const record of records) {
            record.addedNodes.forEach(node => translateAddedContent(node, selector ? selector.value : language));
        }
    }).observe(document.body, { childList: true, subtree: true });
